"""
Differentiate finite-time stretching twice in a moving harmonic-energy metric.

The harmonic-energy norm in the moving anchored frame is defined by

$$D(\lambda)=\operatorname{diag}(K(\lambda)^{1/2},I),\qquad

A(\lambda)=D(\lambda)M(\lambda)D(\lambda)^{-1},$$

where the square root is the principal positive-definite matrix square root. Its derivatives satisfy Sylvester equations, so the derivative of $D$ cannot in general be obtained by scalar differentiation of diagonal entries. Inverse responses obey

$$ (D^{-1})'=-D^{-1}D'D^{-1},$$

$$ (D^{-1})''=2D^{-1}D'D^{-1}D'D^{-1}-D^{-1}D''D^{-1}.$$

All three factors in the similarity transform contribute to $A'$ and $A''$.



Set $G=A^TA$ and let its simple largest eigenvalue be $\rho$ with unit vector $v$. Then

$$\rho'=v^TG'v,\qquad

(\rho I-G+vv^T)v'=(I-vv^T)G'v,$$

$$\rho''=v^TG''v+2(v')^TG'v.$$

The bordered resolvent fixes $v^Tv'=0$ and permits repeated non-leading eigenvalues. For period $T$, define $\chi=\log\sigma_{\max}(A)/T=\log\rho/(2T)$; its curvature is

$$\chi''=\frac1{2T}\left(\frac{\rho''}{\rho}-\frac{(\rho')^2}{\rho^2}\right).$$

Thus a second derivative of stretching includes both the motion of the singular direction and the changing reference-energy metric. A contraction of $A''$ with fixed singular vectors alone is incomplete. The output keeps nominal stretching and its first derivative as diagnostic quantities in addition to the curvature.

Returns
-------
np.ndarray, shape (4,), singular value, log-stretching rate, slope, and curvature in the moving metric.
"""

# =============================================================================
