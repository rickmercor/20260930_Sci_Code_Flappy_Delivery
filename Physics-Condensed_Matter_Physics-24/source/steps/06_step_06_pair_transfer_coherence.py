"""
Return the magnitude of the coherence that transfers an electron pair from the second impurity orbital to the first, evaluated in the supplied thermal state. Invalid input raises ValueError: the two size arguments must be positive integers and rho must be square with the full Fock-space dimension.

Besides spin exchange between the two singly occupied configurations, a second coherence can connect the configurations in which both electrons occupy the same orbital, and it is the expectation value of an operator that annihilates a pair on one orbital and creates one on the other. This amplitude connects two different local charge sectors, one holding both electrons on the first orbital and the other holding both on the second, so an operational restriction to measurements that respect local particle number dephases it away. Computing it is therefore a diagnostic rather than an ingredient: when the interaction contains a pair-hopping term the coherence is genuinely nonzero, which shows the dephasing removes a real quantity instead of one that had already vanished.

Returns
-------
float, the magnitude of the impurity pair-transfer coherence
"""

# =============================================================================
# FUNCTION SIGNATURE (shown to the LLM)
# =============================================================================

import numpy as np


def pair_transfer_coherence(rho, n_orb, n_bath_per_orb):
    """Compute the magnitude of the impurity pair-transfer coherence.

    Parameters
    ----------
    rho : array_like
        Many-body density matrix in the occupation-number basis.
    n_orb : int
        Number of impurity orbitals.
    n_bath_per_orb : int
        Number of bath levels attached to each orbital.

    Returns
    -------
    value : float
        Magnitude of the coherence that transfers an impurity pair from
        orbital one to orbital zero.
    
    Raises
    ------
    ValueError
        If ``n_orb`` or ``n_bath_per_orb`` is not a positive integer, or if
        ``rho`` is not a square matrix of the full Fock-space dimension.
    """
    return None

