"""
Return the weights of four retained local configurations of a two-orbital impurity, ordered as a doubly occupied first orbital with an empty second, an up electron on the first with a down electron on the second, a down electron on the first with an up electron on the second, and an empty first orbital with a doubly occupied second. Invalid input raises ValueError: the two size arguments must be positive integers and rho must be square with the full Fock-space dimension.

Treating two correlated orbitals as an effective pair of two-level systems means keeping only those configurations in which the two electrons either occupy separate orbitals or form a double occupation on one orbital while the other stays empty. The weights are expectation values of projectors assembled from impurity occupation numbers, evaluated in the full thermal state. They are deliberately left unnormalized, so they generally sum to less than one because other total-charge sectors retain finite probability. The two double-occupation weights quantify charge configurations, while the two separate-occupation weights quantify the spin configurations whose coherence carries the entanglement.

Returns
-------
numpy.ndarray, the four unnormalized retained configuration weights
"""

