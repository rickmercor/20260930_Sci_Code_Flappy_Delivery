"""
Calculate the invasion and feedback coefficients with their mixed environmental derivatives.

The generalized mutation reduction uses the difference in focal growth gradients and resource impacts; nonlinear uptake makes these gradients vary on the stationary branch. The parent-induced resource displacement remains part of invasion fitness.

Returns
-------
Shape (4,2), columns invasion fitness s and ecological feedback eta, rows value, epsilon, zeta, epsilon-zeta, without factorial scaling. These are the generalized consumer-resource cavity coefficients giving reduced selection s-eta*f. Use focal growth (1-leakage)sum q and net depletion (I-leakageB)@q, retain the parent-induced invasion correction, and differentiate focal growth gradients as well as resource impacts and susceptibility. The coefficients may have either sign.
"""

