def _oracle_linear_coefficient_A1(J: "np.ndarray", X: "np.ndarray", Gamma: "np.ndarray", A2: "np.ndarray") -> "np.ndarray":
    import numpy as np
    J = np.asarray(J, dtype=float)
    X = np.asarray(X, dtype=float)
    Gamma = np.asarray(Gamma, dtype=float)
    A2 = np.asarray(A2, dtype=float)
    if A2.shape[0] != A2.shape[1]:
        raise ValueError("A2 must be square")
    if X.shape[0] != A2.shape[0]:
        raise ValueError("X and A2 have incompatible shapes")
    XJ2G = X @ (J @ J) @ Gamma @ X.T
    A1 = -A2 @ XJ2G @ A2
    A1 = 0.5 * (A1 + A1.T)
    return A1

