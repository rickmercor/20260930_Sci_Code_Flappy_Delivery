import numpy as np
from scipy.linalg import solve_banded, eigvalsh_tridiagonal
from scipy.optimize import root, brentq
from scipy.special import logsumexp


def _oracle_stationary_profile(
    kappa: float,
    geometry: "np.ndarray",
) -> "np.ndarray":
    geometry = np.asarray(geometry, dtype=float)

    if (
        not np.isfinite(kappa)
        or not -0.65 <= kappa <= -0.15
        or geometry.ndim != 2
        or geometry.shape[1] != 4
        or len(geometry) < 2
        or not np.all(np.isfinite(geometry))
        or np.any(geometry[:, 1] <= 0)
    ):
        raise ValueError("Invalid stationary-family inputs")

    n = len(geometry)
    r, w, c, ld = np.asarray(geometry).T

    def _residual(x, k):
        return _oracle_action_jet(x, k, geometry)[3 : 3 + n] / np.sqrt(w)

    def _jac(x, k):
        diagonal = _oracle_action_jet(x, k, geometry)[3 + n :]
        return (
            np.diag(diagonal)
            + np.diag(-c[:-1] / w[:-1], 1)
            + np.diag(-c[:-1] / w[1:], -1)
        )

    def _attempt(k, guess):
        fit = root(
            _residual,
            guess,
            args=(k,),
            jac=_jac,
            tol=2e-11,
        )
        x = fit.x
        good = (
            np.max(abs(_residual(x, k)) / (1 + abs(x) ** 3)) < 3e-9
            and x[0] > 0.2
            and x.min() > -1e-8
            and np.max(np.diff(x)) < 1e-6
        )
        return x, good

    # Tridiagonal Newton continuation stays on the positive radial branch.
    rho = 1.0
    x = (
        4
        * np.sqrt(3)
        * rho
        / (rho * rho + r * r)
        * np.exp(-0.3 * r)
    )

    good = True

    continuation = np.r_[
        -0.5,
        np.linspace(
            -0.5,
            kappa,
            max(2, int(abs(kappa + 0.5) / 0.012) + 2),
        )[1:],
    ]

    for k in continuation:
        for iteration in range(45):
            jet = _oracle_action_jet(x, k, geometry)
            gradient = jet[3 : 3 + n]

            if np.max(abs(gradient)) < 2e-8:
                break

            off = -c[:-1] / np.sqrt(w[:-1] * w[1:])
            band = np.zeros((3, n))
            band[1] = jet[3 + n :]
            band[0, 1:] = off
            band[2, :-1] = off

            x += solve_banded(
                (1, 1),
                band,
                -gradient,
            ) / np.sqrt(w)
        else:
            good = False
            break

    good = (
        good
        and x[0] > 0.2
        and x.min() > -1e-8
        and np.max(np.diff(x)) < 1e-6
    )

    if not good:
        rho = -2 * kappa
        guess = (
            4
            * np.sqrt(3)
            * rho
            / (rho * rho + r * r)
            * np.exp(-0.3 * r)
        )
        x, good = _attempt(kappa, guess)

    if not good:
        raise RuntimeError(
            "Positive decreasing stationary profile failed to converge"
        )

    return x

