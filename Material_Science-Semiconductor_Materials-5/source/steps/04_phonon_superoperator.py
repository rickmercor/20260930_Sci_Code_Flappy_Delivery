"""
Construct the nonsecular phonon generator series.

Interference between bath-resolved transitions contributes at successive orders in the probe couplings.

Returns
-------
result : np.ndarray     Complex shape (K+1,D*D,D*D), ordinary Taylor coefficients of the     complete nonsecular Born–Markov phonon generator determined by     the supplied coupling and causal rate operators. Coefficient k     has units ps**(k-1). The matrix representation stacks density-matrix     columns, so vec_F(K_k[rho])=result[k]@vec_F(rho).
"""

# =============================================================================
# FUNCTION SIGNATURE (shown to the LLM)
# =============================================================================

def phonon_superoperator(coupling_operator: "np.ndarray", rate_series: "np.ndarray") -> "np.ndarray":
    """Represent the full phonon generator coefficient by coefficient.

    Parameters
    ----------
    coupling_operator : np.ndarray
        Dimensionless Hermitian shape (D,D), the phonon coupling A.
    rate_series : np.ndarray
        Complex shape (K+1,D,D), 0<=K<=6, ordinary Taylor coefficients
        of the joint rate operator for a real coupling scale lambda.

    Returns
    -------
    result : np.ndarray
        Complex shape (K+1,D*D,D*D), ordinary Taylor coefficients of the
        complete nonsecular Born–Markov phonon generator determined by
        the supplied coupling and causal rate operators. Coefficient k
        has units ps**(k-1). The matrix representation stacks density-matrix
        columns, so vec_F(K_k[rho])=result[k]@vec_F(rho).
    """
    return result

# =============================================================================
# GOLD SOLUTION
# =============================================================================

import numpy as np

def _oracle_phonon_superoperator(coupling_operator: "np.ndarray", rate_series: "np.ndarray") -> "np.ndarray":
    a=coupling_operator;eye=np.eye(len(a));result=[]
    for z in rate_series:
        result.append(-np.kron(eye,a@z)+np.kron(a.T,z)+np.kron(z.conj(),a)-np.kron((z.conj().T@a).T,eye))
    return np.array(result)

