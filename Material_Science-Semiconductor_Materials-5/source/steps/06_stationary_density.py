"""
Recover the normalized stationary family coefficient by coefficient.

The vanishing sensor populations are resolved by the stationary family’s coefficients at the orders that contribute to each photon coincidence.

Returns
-------
result : np.ndarray     Complex shape (K+1,D,D), ordinary coefficients rho_k of the common     stationary family satisfying L(lambda)vec_F(rho(lambda))=0 and     Tr(rho(lambda))=1 through order K. Coefficient k is Hermitian and     has units ps**k; the derivative factorial denominator is included.
"""

# =============================================================================
# FUNCTION SIGNATURE (shown to the LLM)
# =============================================================================

def stationary_density(generators: "np.ndarray") -> "np.ndarray":
    """Solve for the stationary density-matrix Taylor coefficients.

    Parameters
    ----------
    generators : np.ndarray
        Complex shape (K+1,D*D,D*D), 0<=K<=6, ordinary Taylor coefficients
        of a trace- and Hermiticity-preserving generator for real lambda.
        Matrices use column vectorization. L(0) has a unique trace-one
        stationary state and a nonsingular trace-constrained system.

    Returns
    -------
    result : np.ndarray
        Complex shape (K+1,D,D), ordinary coefficients rho_k of the common
        stationary family satisfying L(lambda)vec_F(rho(lambda))=0 and
        Tr(rho(lambda))=1 through order K. Coefficient k is Hermitian and
        has units ps**k; the derivative factorial denominator is included.
    """
    return result

# =============================================================================
# GOLD SOLUTION
# =============================================================================

import numpy as np
from scipy.linalg import lu_factor, lu_solve

def _oracle_stationary_density(generators: "np.ndarray") -> "np.ndarray":
    order = len(generators)-1
    d = int(round(np.sqrt(generators.shape[1])))
    matrix = generators[0].copy()
    matrix[0] = np.eye(d).ravel(order='F')
    factor = lu_factor(matrix)
    states = []
    for k in range(order+1):
        rhs = np.zeros(d*d, complex)
        if k == 0:
            rhs[0] = 1
        else:
            for j in range(1, k+1):
                rhs -= generators[j] @ states[k-j]
            rhs[0] = 0
        state = lu_solve(factor, rhs).reshape((d,d), order='F')
        states.append(((state+state.conj().T)/2).ravel(order='F'))
    return np.array([x.reshape((d,d),order='F') for x in states])

