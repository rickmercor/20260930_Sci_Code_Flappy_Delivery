"""
Posterior prediction of the driven spherical-64 child.

For $a=(\Re C,\Im C,\Re E,\Im E)$ and each real child coordinate $f_i(a)=a^TA_i a$, build the matrices generated by



$$h_{64}^{(2)}=\mathcal R_{64}^{22}C^2e^{-2i\omega_{220}t}+2\mathcal R_{64}^{23}CEe^{-i(\omega_{220}+\omega_{320})t}.$$



Use the exact Gaussian moments



$$E[f_i]=\bar a^TA_i\bar a+\operatorname{tr}(A_iV),$$

$$\operatorname{Cov}(f_i,f_j)=2\operatorname{tr}(A_iVA_jV)+4\bar a^TA_iVA_j\bar a.$$



Treat those moments as a task-defined Gaussian predictive closure. First condition the complete waveform error on the complete residual vector as in step 06, and partition the resulting mean and covariance into parent and child blocks. With $G=K_{cp}K_{pp}^{-1}$, $B=GX$, $b=m_c+G(y_p-m_p)$, and row $i$ of $Q=\operatorname{Cov}(f,a)$ equal to $2\bar a^TA_iV$, use



$$

\mu_{64}=E[f]+b-B\bar a,

$$



$$

\Sigma_{64}=\operatorname{Cov}(f)+K_{cc}-GK_{pc}+BVB^T-QB^T-BQ^T.

$$



This conditions the child numerical error on the observed parent waveform as well as on the full residual record. Score $-[r^T\Sigma_{64}^{-1}r+\log|\Sigma_{64}|]/2$. The finite nonnegative response scale multiplies both response coefficients; zero is the zero-response control.



Conditional on each trial state and the observed conditioning scales $A_\beta=\max_t|\Delta_\beta(t)|$, score the supplied residual realizations with



$$d_\beta=(\Re\Delta_\beta(t_0),\ldots,\Re\Delta_\beta(t_6),\Im\Delta_\beta(t_0),\ldots,\Im\Delta_\beta(t_6))$$



and the complete correlated residual covariance $D$ from step 05, add



$$\ell_\Delta=-\frac12\left[d^TD^{-1}d+\log|D|\right].$$



The observed $A_\beta$ receives no density and is not integrated. Factor the state likelihood as $p(d_{22},d_{64})p(h_{22},h_{64}\mid d_{22},d_{64})$; the total state score is the conditional parent score plus the conditional child score plus $\ell_\Delta$.

Returns
-------
`numpy.ndarray` of shape `(n,8)` with `(spin,mass,parent_score,child_score,total_score,child_mahalanobis,Re prediction[0],Im prediction[0])`, where `total_score` includes the two-mode residual score and the final two columns contain the total conditional child predictive mean, compared at `1e-9`.
"""

