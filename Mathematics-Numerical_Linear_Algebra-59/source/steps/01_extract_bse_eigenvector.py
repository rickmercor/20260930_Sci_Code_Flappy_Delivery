"""
Extracts the target eigenpair of the definite Bethe-Salpeter matrix H = [[R, C], [-C, -R]] and reduces it to a real 32-vector v.

A definite Bethe-Salpeter-type matrix $H = \begin{bmatrix} R & C \\ -C & -R \end{bmatrix}$, built from a Hermitian resonant block $R$ and a symmetric coupling block $C$, has real eigenvalues occurring in plus-minus pairs. Exactly one eigenvalue of $H$ lies in a given open interval $(\alpha, \beta)$. This step extracts that eigenvalue and its associated real eigenvector, then derives a single real $32$-vector $v$ from it: normalize the full eigenvector to unit length, keep only its first thirty-two entries, and renormalize that length-$32$ vector to unit length again.







Formulas:







$H = \begin{bmatrix} R & C \\ -C & -R \end{bmatrix}$







$\lambda$: the unique eigenvalue of $H$ with $\alpha < \lambda < \beta$







$x = \begin{bmatrix} x_1 \\ x_2 \end{bmatrix}$: associated real eigenvector ($Hx = \lambda x$)







$\text{vec}_{34} = x / \|x\|_2$







$v = \text{vec}_{34}[:32] / \|\text{vec}_{34}[:32]\|_2$

Returns
-------
v : np.ndarray, length-32 real vector, the extracted and renormalized eigenvector.
"""

