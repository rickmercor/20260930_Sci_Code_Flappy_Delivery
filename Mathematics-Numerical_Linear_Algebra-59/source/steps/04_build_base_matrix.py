import numpy as np


def _oracle_build_base_matrix(e: np.ndarray, U: np.ndarray) -> np.ndarray:
    e = np.asarray(e, dtype=float)
    U = np.asarray(U, dtype=float)
    if e.shape != (32,):
        raise ValueError("e must have shape (32,)")
    if U.shape != (32, 32):
        raise ValueError("U must have shape (32,32)")
    if not np.allclose(U @ U.T, np.eye(32), atol=1e-5):
        raise ValueError("U must be orthogonal")
    s = e - e.min() + 0.5
    A0 = U @ np.diag(s) @ U.T
    A0 = 0.5 * (A0 + A0.T)
    return A0

