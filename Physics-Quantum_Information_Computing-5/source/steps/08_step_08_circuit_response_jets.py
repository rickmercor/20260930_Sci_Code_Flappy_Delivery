"""
Compose differentiated gate propagation, local frame updates and transient pair sweeps.

Start from the supplied normalized-state jet with constant identity local frames and no initial compression.

After every physical gate apply top-$k$ projection, run the finite single-qubit snapshot optimizer, and run one transient brick-wall sweep on all even edges followed by all odd edges, each visited in increasing order.

For $N=5$ the pair sequence is $(0,1),(2,3),(1,2),(3,4)$.

The working coordinates remain related to the physical state by



$$

\psi(s)=[U_{N-1}(s)\otimes\cdots\otimes U_0(s)]v(s).

$$



Return all continuous responses through every supplied derivative order and the product of masses from gate compressions and accepted local trials.

No adaptive trigger, delayed truncation, low-participation bypass or random sampling is used.

All supports, acceptance choices, phase pivots and pass counts use their values at zero; degenerate proposals use constant identity with gap threshold $10^{-10}$ and guards use $10^{-12}$.

For an empty circuit, return the input jet, identity-frame jets and mass jet with base one and every other row zero.

Unit base states and base unitaries use maximum residual tolerance $10^{-9}$; derivative rows are supplied ordinary derivatives, not Taylor coefficients.



A jet has J=3 rows for one real perturbation s, ordered (0,1,2), or J=9 rows for two real perturbations (s,u). For J=9, row 3*a+b is the ordinary partial derivative of orders (a,b), with 0 <= a,b <= 2; in particular rows 4,5,7,8 are (1,1),(1,2),(2,1),(2,2). The rectangular jet includes total orders three and four. All jet-valued arguments in one call use the same J. These are derivatives, not factorial-divided Taylor coefficients. All discrete decisions are fixed at (0,0); every continuous dependence is differentiated.

Returns
-------
The final working-state jet, accumulated frame jets and committed-mass jet in that order.
"""

