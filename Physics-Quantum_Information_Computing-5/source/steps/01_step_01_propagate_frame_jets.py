"""
Propagate supplied derivative orders through a physical gate in evolving local coordinates.

In the one-parameter restriction, the jet contains ordinary derivatives at zero, ordered $(v,v',v'')$, so its local expansion is $v(s)=v+sv'+s^2v''/2+O(s^3)$.

The physical-to-working gate depends on both the physical gate and the current product frame:



$$

\widetilde G(s)=W(s)^\dagger G(s)W(s),\qquad W(s)=U_{q_1}(s)\otimes U_{q_2}(s).

$$



Differentiate the entire action $\widetilde G(s)v(s)$ through every supplied derivative order, including every dependence of $W$.

Global qubit zero is least significant; the ordered local index is $2b_{q_1}+b_{q_2}$ even when $q_1>q_2$.

Amplitudes contributing to the same output index add coherently. No compression occurs here.

Unit base states and base unitaries use maximum residual tolerance $10^{-9}$; derivative rows are supplied ordinary derivatives, not Taylor coefficients.



A jet has J=3 rows for one real perturbation s, ordered (0,1,2), or J=9 rows for two real perturbations (s,u). For J=9, row 3*a+b is the ordinary partial derivative of orders (a,b), with 0 <= a,b <= 2; in particular rows 4,5,7,8 are (1,1),(1,2),(2,1),(2,2). The rectangular jet includes total orders three and four. All jet-valued arguments in one call use the same J. These are derivatives, not factorial-divided Taylor coefficients. All discrete decisions are fixed at (0,0); every continuous dependence is differentiated.

Returns
-------
All supplied complex derivative orders of the propagated working state.
"""

