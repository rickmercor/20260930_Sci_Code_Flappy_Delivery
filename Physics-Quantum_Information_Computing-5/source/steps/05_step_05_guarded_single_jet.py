"""
Accept or reject a lossy single-qubit coordinate response using the base-state guard.

For a proposed local frame $V_j(s)$, apply $V_j(s)^\dagger$ to the current working state, retain the top-$k$ base support and normalize.

Acceptance uses the participation ratio of this compressed trial at zero:



$$

\operatorname{PR}_{\mathrm{old}}(0)-\operatorname{PR}_{\mathrm{trial}}(0)>\varepsilon.

$$



On acceptance, commit all supplied state derivative orders and the product-frame jet of $U_j(s)V_j(s)$.

On rejection, return the complete previous state and frame jets and retained-mass jet with base one and every other row zero.

The decision is fixed at zero; derivatives of comparison operators are not taken.

The retained mass of a rejected candidate is excluded from the committed trajectory.

Unit base states and base unitaries use maximum residual tolerance $10^{-9}$; derivative rows are supplied ordinary derivatives, not Taylor coefficients.



A jet has J=3 rows for one real perturbation s, ordered (0,1,2), or J=9 rows for two real perturbations (s,u). For J=9, row 3*a+b is the ordinary partial derivative of orders (a,b), with 0 <= a,b <= 2; in particular rows 4,5,7,8 are (1,1),(1,2),(2,1),(2,2). The rectangular jet includes total orders three and four. All jet-valued arguments in one call use the same J. These are derivatives, not factorial-divided Taylor coefficients. All discrete decisions are fixed at (0,0); every continuous dependence is differentiated.

Returns
-------
The committed state jet, frame jets, retained-mass jet and numerical acceptance flag in that order.
"""

