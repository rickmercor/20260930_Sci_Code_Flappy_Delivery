# GOLD SOLUTION
# =============================================================================

def _oracle_compute_prediction_interval(
    observed: np.ndarray,
    heldout_predictions: np.ndarray,
    fold_ids: np.ndarray,
    test_fold_predictions: np.ndarray,
    confidence_level: float
) -> np.ndarray:
    import numpy as np

    observed_array = np.asarray(
        observed,
        dtype=float
    )

    if observed_array.ndim != 1:
        raise ValueError(
            "observed must be one-dimensional."
        )

    if observed_array.size == 0:
        raise ValueError(
            "At least one training individual is required."
        )

    residuals = _oracle_compute_cv_residuals(
        observed,
        heldout_predictions
    )

    matched_test_predictions = (
        _oracle_align_test_predictions_by_fold(
            fold_ids,
            test_fold_predictions
        )
    )

    lower_candidates = (
        _oracle_construct_lower_candidates(
            matched_test_predictions,
            residuals
        )
    )

    upper_candidates = (
        _oracle_construct_upper_candidates(
            matched_test_predictions,
            residuals
        )
    )

    ranks = _oracle_compute_interval_ranks(
        observed_array.size,
        confidence_level
    )

    lower_bound = _oracle_select_order_statistic(
        lower_candidates,
        int(ranks[0])
    )

    upper_bound = _oracle_select_order_statistic(
        upper_candidates,
        int(ranks[1])
    )

    if not (
        np.isfinite(lower_bound)
        and np.isfinite(upper_bound)
    ):
        raise ValueError(
            "Prediction interval bounds must be finite."
        )

    if lower_bound > upper_bound:
        raise ValueError(
            "Lower prediction bound cannot exceed upper bound."
        )

    return np.array(
        [
            float(lower_bound),
            float(upper_bound)
        ],
        dtype=float
    )

