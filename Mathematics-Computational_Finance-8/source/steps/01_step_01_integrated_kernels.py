"""
Evaluate the generating kernel of the spatial scheme together with its first and second antiderivatives at a set of signed offsets.

The spatial weights are not generated by differentiating the kernel phi(y) = (y**2 + c**2)**(-5/2) directly but from its antiderivatives: phi1 is the antiderivative of phi that vanishes at the origin (it is odd), and phi2 is the antiderivative of phi1 whose value at the origin is 1/(3 c**3), which is the closed form the source uses. Because phi2 is used without polynomial augmentation, that integration constant is part of the scheme and must not be normalised away.

Returns
-------
np.ndarray, float, shape (m, 3): column 0 phi(y), column 1 phi1(y), column 2 phi2(y) at the m offsets, in input order.
"""

