"""
Fit the Padé spectrum at one cutoff and return its observed covariance

Each frequency cutoff defines a separate local likelihood fit. Covariance is the inverse observed Hessian in the original Pade parameters, after undoing numerical scaling.

Returns
-------
Tuple (p,C): real Padé parameters with shape (3,) and observed covariance with shape (3,3).
"""

# =============================================================================
# FUNCTION SIGNATURE (shown to the LLM)
# =============================================================================

def fit_cutoff(frequency: 'np.ndarray', observed: 'np.ndarray', dof: 'np.ndarray', cutoff: float, initial: 'np.ndarray') -> 'tuple[np.ndarray, np.ndarray]':
    """Fit m(f)=(p0+p2*f**2)/(1+q2*f**2) by the likelihood in pade_likelihood.
    
    Parameters
    ----------
    frequency, observed, dof, initial : numpy.ndarray
        Real finite spectral data and starting Padé vector.
    cutoff : float
        Positive finite frequency cutoff.

    frequency, observed and dof obey pade_likelihood's vector contract:
    K>=4, finite strictly increasing f>=0, finite observed>0 and dof>0.
    cutoff is finite and >0. initial is a finite (3,) Pade parameter vector
    with positive numerator and denominator at every supplied frequency.
    w=1/(1+(f/cutoff)**8); replace weights strictly below 0.001 by zero.
    At least four weights must remain nonzero. Return (p,C), shapes (3,),
    (3,3), where p is the interior local minimum reached from initial and
    C is the inverse observed Hessian of the weighted likelihood at p.
    Use no parameter prior, positivity prior, ridge term in the final
    covariance, or hard cutoff at f=cutoff. The valid spectrum domain is
    numerator>0 and denominator>0 at all supplied f; q2 need not be positive.
    The assessed valid inputs have a unique reachable nondegenerate interior
    minimum. Any converged optimizer is accepted (relative p/C error 2e-5).
    For conditioning, scale f by cutoff and y by its weighted mean; transform
    parameters and covariance back. Earlier public pade_likelihood is available.
    
    Returns
    -------
    result
        Tuple (p,C): real Padé parameters with shape (3,) and observed covariance with shape (3,3).
    
    Raises
    ------
    ValueError
        If any input contains complex values, including a complex dtype with
        zero imaginary part.
        On a stated input-contract violation, fewer than four nonzero weights,
        failure to find an interior stationary point, or a nonpositive-definite
        observed Hessian there. No invalid-optimizer cases are used for difficulty.
    
    Notes
    --------------------------
    Import required packages inside the function. NumPy and SciPy are installed.
    An import in test setup does not define a global in this function.
    Implement the public function only; the reference implementation is separate.
    """
    return result

# =============================================================================
# GOLD SOLUTION
# =============================================================================

def _oracle_fit_cutoff(frequency: 'np.ndarray', observed: 'np.ndarray', dof: 'np.ndarray', cutoff: float, initial: 'np.ndarray') -> 'tuple[np.ndarray, np.ndarray]':
    import numpy as np

    for _name, _value in (('frequency', frequency), ('observed', observed), ('dof', dof), ('cutoff', cutoff), ('initial', initial),):
        if np.iscomplexobj(_value):
            raise ValueError(_name + " must be real")

    def _array(x, shape, name):
        try:
            x = np.asarray(x, dtype=float)
        except (ValueError, TypeError, OverflowError) as exc:
            raise ValueError(name) from exc
        if x.shape != shape or not np.all(np.isfinite(x)):
            raise ValueError(name)
        return x

    def _scalar(x, name):
        try:
            a = np.asarray(x, dtype=float)
        except (ValueError, TypeError, OverflowError) as exc:
            raise ValueError(name) from exc
        if a.shape != () or not np.isfinite(a):
            raise ValueError(name)
        return float(a)

    def _spectrum(f, observed, dof):
        try:
            f = np.asarray(f, dtype=float)
        except (ValueError, TypeError, OverflowError) as exc:
            raise ValueError('frequency') from exc
        if f.ndim != 1 or len(f)<4 or not np.isfinite(f).all() or np.any(f<0) or np.any(np.diff(f)<=0):
            raise ValueError('frequency')
        y = _array(observed, f.shape, 'observed')
        nu = _array(dof, f.shape, 'dof')
        if np.any(y<=0) or np.any(nu<=0):
            raise ValueError('observed and dof must be positive')
        return f,y,nu

    def _pade_jet(p, f):
        x = f*f
        num = p[0]+p[1]*x
        den = 1+p[2]*x
        if np.any(num<=0) or np.any(den<=0):
            raise ValueError('nonpositive Pade numerator or denominator')
        m = num/den
        J = np.stack((1/den,x/den,-num*x/den**2),axis=1)
        D = np.zeros((len(f),3,3))
        D[:,0,2]=D[:,2,0]=-x/den**2
        D[:,1,2]=D[:,2,1]=-x*x/den**2
        D[:,2,2]=2*num*x*x/den**3
        return m,J,D
    f,y,nu=_spectrum(frequency,observed,dof)
    c=_scalar(cutoff,'cutoff'); initial=_array(initial,(3,),'initial')
    if c<=0:raise ValueError('cutoff')
    _pade_jet(initial,f)
    with np.errstate(over='ignore'):
        w=1/(1+(f/c)**8)
    w[w<0.001]=0
    if np.count_nonzero(w)<4:raise ValueError('too few frequencies')
    scale=float(np.sum(w*y)/np.sum(w))
    transform=np.array([scale,scale/c**2,1/c**2])
    x=f/c; Y=y/scale; p=initial/transform
    for iteration in range(250):
        value,g,H=_oracle_pade_likelihood(p,x,Y,nu,w)
        ev=np.linalg.eigvalsh(H)
        shift=max(0.0,1e-7*np.max(abs(ev))-ev[0])
        Hstep=H+shift*np.eye(3)
        d=-np.linalg.solve(Hstep,g)
        descent=float(g@d)
        if ev[0]>0 and -descent<1e-19*(1+np.sum(w*nu)):
            break
        rate=1.0
        accepted=False
        for trial in range(70):
            candidate=p+rate*d
            try:
                newvalue,_,_=_oracle_pade_likelihood(candidate,x,Y,nu,w)
            except ValueError:
                newvalue=np.inf
            # The slack only permits a final Newton correction at roundoff.
            if np.isfinite(newvalue) and newvalue<=value+1e-4*rate*descent+1e-12*(1+abs(value)):
                p=candidate; accepted=True; break
            rate*=0.5
        if not accepted:raise ValueError('line search did not converge')
    else:
        raise ValueError('optimizer did not converge')
    _,g,H=_oracle_pade_likelihood(p,x,Y,nu,w)
    try:
        np.linalg.cholesky(H)
        C=np.linalg.inv(H)
    except np.linalg.LinAlgError as exc:
        raise ValueError('nonpositive Hessian') from exc
    return p*transform,C*transform[:,None]*transform[None,:]

