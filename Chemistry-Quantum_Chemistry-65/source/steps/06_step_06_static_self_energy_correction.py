"""
Compute the static self-energy correction generated by the change of the one-body density matrix away from Hartree-Fock.

A Hartree-Fock starting point makes one-shot GW ionization energies too large, partly because the mean field is built
from an idempotent density that ignores correlation. A static correction to the Fock matrix repairs part of this at no
extra frequency-dependent cost: the Coulomb and exchange potentials are re-evaluated with a correlated one-body density
matrix and the Hartree-Fock potentials are subtracted, which mimics part of the effect of self-consistency. For a
closed-shell system with a per-spin density change Delta (the correlated matrix minus the Hartree-Fock one), both
spins contribute to the Coulomb potential while only the same spin contributes to exchange. The corrected Fock matrix
is then used in the one-hole/one-particle block of the quasiparticle problem.

Returns
-------
numpy.ndarray of shape (n, n): static Coulomb-minus-exchange correction to the Fock matrix in eV
"""

# =============================================================================
# FUNCTION SIGNATURE (shown to the LLM)
# =============================================================================

def static_self_energy_correction(eri: "np.ndarray", density: "np.ndarray", n_occ: int) -> "np.ndarray":
    '''Static Coulomb-minus-exchange potential of the per-spin density change relative to Hartree-Fock.

    Parameters
    ----------
    eri : np.ndarray
        Shape (n, n, n, n), real two-electron integrals (pq|rs) in chemists' notation in the canonical Hartree-Fock
        orbital basis (eV).
    density : np.ndarray
        Shape (n, n), symmetric per-spin correlated one-body density matrix in the same basis; the Hartree-Fock
        reference is 1 on the first n_occ diagonal elements and zero elsewhere.
    n_occ : int
        Number of doubly occupied orbitals, 1 <= n_occ < n.

    Returns
    -------
    sigma : np.ndarray
        Shape (n, n), symmetric correction in eV,
        sigma_pq = sum_{rs} [2 (pq|rs) - (pr|qs)] Delta_rs with Delta = density - density_HF.

    Raises
    ------
    ValueError
        If n_occ is outside 1 <= n_occ < n or the shapes of eri and density do not match.
    '''
    return sigma

# =============================================================================
# GOLD SOLUTION
# =============================================================================

import numpy as np


def _oracle_static_self_energy_correction(eri: "np.ndarray", density: "np.ndarray", n_occ: int) -> "np.ndarray":
    """Reference implementation."""
    import numpy as np
    v4 = np.asarray(eri, dtype=float)
    dens = np.asarray(density, dtype=float)
    n = dens.shape[0]
    o = int(n_occ)
    if dens.shape != (n, n) or v4.shape != (n, n, n, n):
        raise ValueError("eri must have shape (n, n, n, n) and density shape (n, n)")
    if not 1 <= o < n:
        raise ValueError("n_occ must satisfy 1 <= n_occ < n")
    delta = dens.copy()
    delta[np.arange(o), np.arange(o)] -= 1.0
    return 2.0 * np.einsum('pqrs,rs->pq', v4, delta) - np.einsum('prqs,rs->pq', v4, delta)

